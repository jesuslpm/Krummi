// SQL Server order vectors for Krummi (AC17 of the tables with schema PRD, document 3 of the table design).
//
// Writes uuids in the byte order of RFC 9562, one per line as 32 lowercase hexadecimal digits, sorted with .NET's
// System.Data.SqlTypes.SqlGuid, a reference independent of Krummi: the vectors pin .NET's semantics of SQL Server's
// uniqueidentifier order, not results of a SQL Server instance. The Rust test `sql_server_order_matches_sqlguid_vectors`
// (crates/krummi/tests/table_encoding.rs) checks that Krummi's SQL Server key encoding sorts them in the file's order.
//
// The values are generated once, from a fixed seed, and committed. To generate them again, from the repository root:
//
//   dotnet run --project tools/sqlguid-vectors -c Release -- crates/krummi/tests/data/sqlserver-order/sqlguid-order.txt
//
// The same seed gives the same file on every run and platform.

using System.Data.SqlTypes;
using System.Text;

if (args.Length != 1)
{
    Console.Error.WriteLine("usage: sqlguid-vectors <output file>");
    return 2;
}

const int Seed = 20261110;
var random = new Random(Seed);

// The groups SQL Server compares, most significant first, as byte ranges of Guid.ToByteArray() (.NET layout).
int[][] groups = [[10, 11, 12, 13, 14, 15], [8, 9], [6, 7], [4, 5], [0, 1, 2, 3]];

// Each group takes one of four values (all 00, all FF and two random ones), so many uuids tie on the groups SQL
// Server compares first and each group decides the order of some pairs.
var pools = groups
    .Select(group => new[]
    {
        new byte[group.Length],
        Enumerable.Repeat((byte)0xFF, group.Length).ToArray(),
        RandomBytes(group.Length),
        RandomBytes(group.Length),
    })
    .ToArray();

var guids = new HashSet<Guid>();
for (var i = 0; i < 1500; i++)
{
    var dotnet = new byte[16];
    for (var g = 0; g < groups.Length; g++)
    {
        var value = pools[g][random.Next(4)];
        for (var j = 0; j < groups[g].Length; j++)
        {
            dotnet[groups[g][j]] = value[j];
        }
    }
    guids.Add(new Guid(dotnet));
}
for (var i = 0; i < 500; i++)
{
    guids.Add(new Guid(RandomBytes(16)));
}

var sorted = guids.Select(guid => new SqlGuid(guid)).ToList();
sorted.Sort((a, b) => a.CompareTo(b));

var text = new StringBuilder();
text.Append("# SQL Server order vectors (AC17): uuids in RFC 9562 byte order, sorted with .NET's SqlGuid.\n");
text.Append($"# Generated by tools/sqlguid-vectors with seed {Seed}; see its Program.cs to generate them again.\n");
foreach (var value in sorted)
{
    text.Append(Convert.ToHexString(value.Value.ToByteArray(bigEndian: true)).ToLowerInvariant()).Append('\n');
}
File.WriteAllText(args[0], text.ToString(), new UTF8Encoding(false));
Console.WriteLine($"{sorted.Count} uuids written to {args[0]}");
return 0;

byte[] RandomBytes(int length)
{
    var bytes = new byte[length];
    random.NextBytes(bytes);
    return bytes;
}
