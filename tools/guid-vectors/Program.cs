// Test vectors of Krummi's `ulid` and `uuid` generators (E15 of docs/prd/krummi/tables-schema.prd.md, AC12).
//
// An independent reference written in C#: it applies the three rules of E15 to fixed clock readings and fixed random
// bits, lays the values out as E15 says (the sequential `uuid` with the user's .NET layout, `CreateGuid` of
// `SqlSequentialGuid`), checks that each scenario's values sort in generation order (the sequential `uuid` with
// `System.Data.SqlTypes.SqlGuid`, the order SQL Server uses; the others by their 16 bytes) and writes them to
// crates/krummi/tests/data/generators/vectors.txt, which crates/krummi/tests/generators.rs reads.
//
// The vectors were generated once; rerun only to add scenarios, from the repository root:
//
//     dotnet run --project tools/guid-vectors -- crates/krummi/tests/data/generators/vectors.txt
//
// (then delete tools/guid-vectors/bin and tools/guid-vectors/obj). The program fails, writing nothing, if a scenario
// draws random bits where it gives none, gives bits where it draws none, or does not sort in generation order.

using System.Buffers.Binary;
using System.Data.SqlTypes;
using System.Text;

const ulong T = 1_700_000_000_000; // 2023-11-14T22:13:20Z
var max = Generator.MaxMillisecond;

// Random draws, as the 10 bytes (80 bits, big-endian) the operating system would return.
var r1 = Bits("0123456789abcdef0123");
var r2 = Bits("fedcba9876543210fedc");
var r3 = Bits("5a5a5a5a5a5a5a5a5a5a");
var r4 = Bits("00000000000000000001");
var allOnes = Bits("ffffffffffffffffffff");
var allOnesButOne = Bits("fffffffffffffffffffe");
// Low 64 bits one short of all ones: two increments roll every byte of the low part over and carry into the high 16
// bits (bytes 8-9 of the sequential `uuid`); in the `uuid` version 7 the carry crosses its variant bits.
var carry = Bits("1234fffffffffffffffe");

var scenarios = new (string Name, (ulong Clock, UInt128? Random)[] Steps)[]
{
    ("first-millisecond-zero", [(0, r1)]),
    ("new-milliseconds", [(1, r1), (2, r2), (T, r3), (T + 1000, r4)]),
    ("same-millisecond", [(T, r1), (T, null), (T, null)]),
    ("carry-across-groups", [(T, carry), (T, null), (T, null), (T, null)]),
    ("clock-goes-back", [(T, r2), (T - 5, null), (T - 1000, null), (T + 1, r3)]),
    ("overflow-same-millisecond", [(T, allOnesButOne), (T, null), (T, r1), (T + 1, null), (T, null)]),
    ("overflow-clock-behind", [(T, allOnes), (T - 3, r2), (T + 1, null), (T + 5, r3)]),
    ("last-millisecond-exhausted", [(max, allOnesButOne), (max, null), (max, null), (max - 10, null)]),
    ("millisecond-out-of-range", [(max + 1, null), (ulong.MaxValue, null), (max, r4), (max, null)]),
};

var output = new StringBuilder();
output.Append("""
    # Test vectors of the ulid and uuid generators (E15, AC12). Generated by tools/guid-vectors; do not edit by hand.
    # scenario <generator> <name>: a new generator.
    # step <clock ms> <random bytes it draws, hex, or -> <expected value, 16 bytes in RFC 9562 order, hex, or invalid-value>
    # The uuid version 7 takes the low 74 bits of the 80 drawn. The sequential uuid values of each scenario sort in this
    # order with SqlGuid, as SQL Server sorts them.

    """.ReplaceLineEndings("\n"));
foreach (var kind in Enum.GetValues<Kind>())
{
    foreach (var (name, steps) in scenarios)
    {
        output.Append($"\nscenario {KindName(kind)} {name}\n");
        var generator = new Generator(kind);
        var values = new List<byte[]>();
        foreach (var (clock, random) in steps)
        {
            var drew = false;
            var value = generator.Next(clock, () =>
            {
                drew = true;
                return random ?? throw new InvalidOperationException($"{name}: draw at {clock} without bits");
            });
            if (random is not null && !drew)
            {
                throw new InvalidOperationException($"{name}: bits given at {clock} but not drawn");
            }
            var drawn = random is UInt128 r ? Convert.ToHexString(Bytes(r)).ToLowerInvariant() : "-";
            var expected = value is null ? "invalid-value" : Convert.ToHexString(value).ToLowerInvariant();
            output.Append($"step {clock} {drawn} {expected}\n");
            if (value is not null)
            {
                values.Add(value);
            }
        }
        CheckGenerationOrder(kind, name, values);
    }
}
var path = args.Length > 0 ? args[0] : "vectors.txt";
File.WriteAllText(path, output.ToString());
Console.WriteLine($"wrote {path}");

static UInt128 Bits(string hex)
{
    var bytes = Convert.FromHexString(hex);
    UInt128 value = 0;
    foreach (var b in bytes)
    {
        value = (value << 8) | b;
    }
    return value;
}

static byte[] Bytes(UInt128 bits)
{
    var bytes = new byte[10];
    for (var i = 9; i >= 0; i--)
    {
        bytes[i] = (byte)bits;
        bits >>= 8;
    }
    return bytes;
}

static string KindName(Kind kind) => kind switch
{
    Kind.Ulid => "ulid",
    Kind.UuidV7 => "uuid-v7",
    Kind.SequentialUuid => "sequential-uuid",
    _ => throw new ArgumentOutOfRangeException(nameof(kind)),
};

// The values of a scenario sort in generation order: by SqlGuid for the sequential uuid, by their bytes otherwise.
static void CheckGenerationOrder(Kind kind, string name, List<byte[]> values)
{
    var sorted = kind == Kind.SequentialUuid
        ? values.OrderBy(v => new SqlGuid(Generator.FromRfcBytes(v))).ToList()
        : values.OrderBy(v => Convert.ToHexString(v).ToLowerInvariant(), StringComparer.Ordinal).ToList();
    for (var i = 0; i < values.Count; i++)
    {
        if (!ReferenceEquals(sorted[i], values[i]) || (i > 0 && values[i].AsSpan().SequenceEqual(values[i - 1])))
        {
            throw new InvalidOperationException($"{KindName(kind)} {name}: not in generation order at {i}");
        }
    }
}

enum Kind
{
    Ulid,
    UuidV7,
    SequentialUuid,
}

// One generator with the three rules of E15.
sealed class Generator(Kind kind)
{
    public const ulong MaxMillisecond = (1UL << 48) - 1;

    readonly UInt128 mask = (UInt128.One << (kind == Kind.UuidV7 ? 74 : 80)) - 1;
    ulong? lastMillisecond;
    UInt128 lastRandom;

    // The next value in RFC 9562 byte order, or null for a millisecond past 48 bits (invalid value). A failed call
    // changes nothing.
    public byte[]? Next(ulong clock, Func<UInt128> draw)
    {
        ulong millisecond;
        UInt128 random;
        if (lastMillisecond is ulong last && clock <= last)
        {
            if (lastRandom < mask)
            {
                // Rule 2: the same millisecond, or the clock went back: the last millisecond, random part plus 1.
                millisecond = last;
                random = lastRandom + 1;
            }
            else
            {
                // Rule 3: the random part overflows: the next millisecond, new bits.
                if (last == MaxMillisecond)
                {
                    return null;
                }
                millisecond = last + 1;
                random = draw() & mask;
            }
        }
        else
        {
            // Rule 1: a later millisecond: new bits.
            if (clock > MaxMillisecond)
            {
                return null;
            }
            millisecond = clock;
            random = draw() & mask;
        }
        lastMillisecond = millisecond;
        lastRandom = random;
        return kind switch
        {
            Kind.Ulid => Ulid(millisecond, random),
            Kind.UuidV7 => UuidV7(millisecond, random),
            _ => ToRfcBytes(CreateGuid((long)millisecond, (ushort)(random >> 64), (ulong)random)),
        };
    }

    // 48 bits of milliseconds and 80 random bits, big-endian.
    static byte[] Ulid(ulong millisecond, UInt128 random)
    {
        var bytes = new byte[16];
        BinaryPrimitives.WriteUInt64BigEndian(bytes.AsSpan(0, 8), millisecond << 16);
        BinaryPrimitives.WriteUInt16BigEndian(bytes.AsSpan(6, 2), (ushort)(random >> 64));
        BinaryPrimitives.WriteUInt64BigEndian(bytes.AsSpan(8, 8), (ulong)random);
        return bytes;
    }

    // RFC 9562 §5.7: unix_ts_ms (48), ver = 7 (4), rand_a (12), var = 0b10 (2), rand_b (62); the 74 random bits are
    // rand_a then rand_b.
    static byte[] UuidV7(ulong millisecond, UInt128 random)
    {
        var randA = (ushort)(random >> 62);
        var randB = (ulong)random & ((1UL << 62) - 1);
        var bytes = new byte[16];
        BinaryPrimitives.WriteUInt64BigEndian(bytes.AsSpan(0, 8), millisecond << 16);
        bytes[6] = (byte)(0x70 | (randA >> 8));
        bytes[7] = (byte)randA;
        BinaryPrimitives.WriteUInt64BigEndian(bytes.AsSpan(8, 8), randB | (1UL << 63));
        return bytes;
    }

    // `CreateGuid` of the user's `SqlSequentialGuid` (WebApi.Entities.Guids), its little-endian branch written with
    // big-endian writes: the bytes of `Guid.ToByteArray`, 8-15 the millisecond (8-9 then overwritten by r0), 0-3, 4-5
    // and 6-7 the low 64 bits from least to most significant group, each big-endian.
    static Guid CreateGuid(long unixTimeMilliseconds, ushort r0, ulong r1)
    {
        Span<byte> bytes = stackalloc byte[16];
        BinaryPrimitives.WriteInt64BigEndian(bytes[8..], unixTimeMilliseconds);
        BinaryPrimitives.WriteUInt32BigEndian(bytes[0..], (uint)r1);
        BinaryPrimitives.WriteUInt16BigEndian(bytes[4..], (ushort)(r1 >> 32));
        BinaryPrimitives.WriteUInt16BigEndian(bytes[6..], (ushort)(r1 >> 48));
        BinaryPrimitives.WriteUInt16BigEndian(bytes[8..], r0);
        return new Guid(bytes);
    }

    // The RFC 9562 byte order of a Guid: the order of its text form.
    static byte[] ToRfcBytes(Guid guid) => guid.ToByteArray(bigEndian: true);

    public static Guid FromRfcBytes(byte[] bytes) => new(bytes, bigEndian: true);
}
